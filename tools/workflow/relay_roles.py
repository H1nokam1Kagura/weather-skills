"""Container-side live role transport: ``ask(role, payload)`` through a host-side Kong relay.

Owner ruling ``container_route_ruling_2026-10-13.live_roles``: live role calls go from the
container to a host-side Kong relay and the Kong key never enters the container. This module
holds no key and never reads one. It authenticates to the relay with a per-run shared token
(random, generated by the relay, passed in through the environment); that token is not a Kong
credential and only opens the relay for one run. ``from_env`` removes every ``SIMKIT_RELAY_*``
name from the environment it read, so tool children started later never inherit the token
(``catalog.child_environment`` copies the whole environment).

Same ``ask(role, payload)`` contract and attributes as ``agents.Roles`` / ``kong_roles.KongRoles``
(``receipts``, ``spent``, ``budget``, ``model``, ``sessions``, ``dispatch_*``, ``processes``).
Each receipt is exactly the KongRoles receipt produced on the host plus ``relay_id``,
``transport_encoding`` and ``transport_bytes`` (``RELAY_RECEIPT_FIELDS``); its
``session_id`` must be the provider's ``response_id`` (observed, never minted before the call).

Deliberately stdlib + ``contracts`` only, so it can be copied into a container with
``tools/workflow/{__init__,contracts,profiles,relay_roles}.py`` and nothing else.

Outcome semantics (mirrors KongRoles; UNKNOWN never becomes success):
- ``Refused``: nothing was sent (bad role, budget, size cap, relay unreachable before any byte
  was written, relay refused before forwarding), or a definite answer came back and is not a
  valid role answer. Every raise carries a frozen gate code; the relay's spend-guard refusal
  (``reason_code: relay_spend_cap``) is ``Refused(gate="budget")``.
- ``RelayOutcomeUnknown``: a request may have reached the relay (and so the gateway) and no
  valid definite answer was observed: timeout or reset after sending, unparseable or
  oversized relay response, or the relay itself reports the Kong outcome UNKNOWN. The budget
  reservation is kept, because the call may have been billed. Every UNKNOWN record carries
  ``fault_class`` / ``fault_kind`` (``classify_fault``) for the rerun ruling.

Spend: the remaining ceiling is reserved before sending and reconciled to the receipt's priced
``cost_usd`` (the host prices every call from its pinned list-price table), so a run makes as
many calls as its budget allows. An unpriced receipt keeps the reservation (fail closed). The
authoritative caps are the relay's own (``relay/kong_relay_host.py`` SpendGuard).

Retries: one ``ask`` is at most one relay request, except the frozen pre-write transport retry
(CAP-TRANSPORT-RETRY): ``_transport_call`` mirrors ``recovery.transport_call`` (a parity test
pins it) and retries once only when the exchange wrote no byte (``RelayTransport.serial`` did
not move) and the controller's ``transport_retry_recorder`` recorded the retry durably.

Transport encoding ``dedup-sha256/1`` (live sub-wave 2, ``live-role-payload-sizes.json``): the
controller's planner/repairer/reviewer payloads carry the same ~55 KB of skill documentation
twice (``documentation`` and ``review_evidence(_request).sources``), which puts the request
body over the cap. The LIVE TRANSPORT deduplicates it losslessly; the controller payload, its
recorded role input files and ``input_hash`` are untouched. ``dedup_encode`` replaces every
JSON value (string or subtree) whose serialization is at least ``DEDUP_MIN_BYTES`` and that
occurs two or more times with ``{"$shared": "<sha256 of its json.dumps text>"}`` and stores it
once in a top-level ``shared`` table (first-appearance order, entries themselves encoded the
same way). The body declares ``original_sha256`` (``contracts.digest`` of the payload, the
receipt ``input_hash``) and ``original_text_sha256`` (sha256 of ``json.dumps(payload)``, which
also pins key order). The host decodes with ``dedup_decode`` and refuses on any mismatch
(``reason_code: dedup_mismatch``, nothing forwarded). When nothing repeats, or the payload
itself holds a ``{"$shared": ...}`` object, encoding is SKIPPED ENTIRELY: the body is exactly
``{"role", "payload"}`` as before and the receipt says ``transport_encoding: null``.
"""

