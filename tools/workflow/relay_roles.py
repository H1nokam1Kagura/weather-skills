def classify_fault(status=None, error_type=None, kind=None):
    """{fault_class, fault_kind} for a failed call. ``kind`` names a deterministic local cause
    (a relay refusal code, ``invalid_answer``, ``harness_error``) and wins when given."""
    if kind is not None:
        return {"fault_class": DETERMINISTIC, "fault_kind": kind}
    if type(status) is int:
        if status == 429:
            return {"fault_class": TRANSIENT, "fault_kind": "http_429"}
        if 500 <= status <= 599:
            return {"fault_class": TRANSIENT, "fault_kind": "http_5xx"}
        return {"fault_class": DETERMINISTIC, "fault_kind": f"http_{status // 100}xx"}
    if error_type in TIMEOUT_ERRORS:
        return {"fault_class": TRANSIENT, "fault_kind": "timeout"}
    if error_type in RESET_ERRORS:
        return {"fault_class": TRANSIENT, "fault_kind": "connection_reset"}
    # No HTTP status was observed: an UNKNOWN with no gateway response.
    return {"fault_class": TRANSIENT, "fault_kind": "no_gateway_response"}


def role_gate(role):
    return ROLE_GATES.get(role, "transition")


# ------------------------------------------------------------------ dedup-sha256/1


class DedupMismatch(ValueError):
    """An encoded body that does not decode to exactly the payload it declares."""


def _text(value):
    return json.dumps(value, allow_nan=False)  # the serializer the role input is sent with


def _sha(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _is_ref(node):
    return isinstance(node, dict) and len(node) == 1 and SHARED_KEY in node


def dedup_encode(payload, min_bytes=DEDUP_MIN_BYTES):
    """The extra body fields for ``payload`` under DEDUP_ENCODING, or None to send it plain.

    Deterministic: the same payload always yields the same encoding. A shared value is keyed by
    the sha256 of its exact ``json.dumps`` text (key order included), so decoding restores the
    identical serialization. None when no value of at least ``min_bytes`` repeats, or when the
    payload already holds an object shaped like a reference (it could not be told apart)."""
    counts = {}

    def count(node):
        if _is_ref(node):
            raise DedupMismatch("payload holds a reference-shaped object")
        children = (
            node.values() if isinstance(node, dict) else node if isinstance(node, list) else ()
        )
        for child in children:
            count(child)
        if isinstance(node, (dict, list, str)):
            text = _text(node)
            if len(text.encode("utf-8")) >= min_bytes:
                counts[text] = counts.get(text, 0) + 1

    try:
        count(payload)
    except DedupMismatch:
        return None
    repeated = {text for text, n in counts.items() if n >= 2}
    if not repeated:
        return None
    shared = {}

    def inner(node):
        if isinstance(node, dict):
            return {key: replace(value) for key, value in node.items()}
        if isinstance(node, list):
            return [replace(value) for value in node]
        return node

    def replace(node):
        if isinstance(node, (dict, list, str)):
            text = _text(node)
            if text in repeated:
                ref = _sha(text)
                if ref not in shared:
                    shared[ref] = None  # reserve first-appearance order, outer before inner
                    shared[ref] = inner(node)
                return {SHARED_KEY: ref}
        return inner(node)

    encoded = inner(payload)  # the root itself is never a reference
    return {
        "payload": encoded,
        "transport_encoding": DEDUP_ENCODING,
        "shared": shared,
        "original_sha256": digest(payload),
        "original_text_sha256": _sha(_text(payload)),
    }


def dedup_decode(request):
    """The original payload of an encoded request (``ENCODED_KEYS``); DedupMismatch unless every
    shared entry hashes to its key, every reference resolves, every entry is used, and the
    result matches both declared hashes."""
    if request.get("transport_encoding") != DEDUP_ENCODING:
        raise DedupMismatch("unknown transport encoding")
    shared = request.get("shared")
    if not isinstance(shared, dict) or not shared:
        raise DedupMismatch("shared table missing or empty")
    resolved, resolving, used = {}, set(), set()

    def resolve(ref):
        if not isinstance(ref, str) or ref not in shared:
            raise DedupMismatch("reference to an unknown shared value")
        used.add(ref)
        if ref not in resolved:
            if ref in resolving:
                raise DedupMismatch("cyclic shared reference")
            resolving.add(ref)
            value = walk(shared[ref])
            resolving.discard(ref)
            if _sha(_text(value)) != ref:
                raise DedupMismatch("shared value does not hash to its reference")
            resolved[ref] = value
        return json.loads(json.dumps(resolved[ref]))  # a detached copy per position

    def walk(node):
        if _is_ref(node):
            return resolve(node[SHARED_KEY])
        if isinstance(node, dict):
            return {key: walk(value) for key, value in node.items()}
        if isinstance(node, list):
            return [walk(value) for value in node]
        return node

    try:
        payload = walk(request.get("payload"))
        text = _text(payload)
    except (TypeError, ValueError, RecursionError) as exc:
        if isinstance(exc, DedupMismatch):
            raise
        raise DedupMismatch(f"encoded payload does not decode: {type(exc).__name__}") from exc
    if used != set(shared):
        raise DedupMismatch("shared table holds an unreferenced value")
    if digest(payload) != request.get("original_sha256"):
        raise DedupMismatch("decoded payload does not match original_sha256")
    if _sha(text) != request.get("original_text_sha256"):
        raise DedupMismatch("decoded payload text does not match original_text_sha256")
    return payload


class RelayOutcomeUnknown(RuntimeError):
    """A request may have reached the relay/gateway and no valid answer was observed."""

    outcome = "UNKNOWN"

    def __init__(self, message, evidence=None):
        super().__init__(message)
        self.evidence = evidence or {}


def _finite(value):
    return type(value) in (int, float) and math.isfinite(value) and value >= 0


def _transport_call(roles, role, call, invocation_id=None):
    """Mirror of ``recovery.transport_call`` (parity-tested), kept here so this module stays
    stdlib + contracts. Retry once, inside the same attempt, on a reset/abort observed BEFORE
    any byte was written (``roles.processes.serial`` did not move) and only when the
    controller's duck-typed ``transport_retry_recorder`` recorded it durably."""
    processes = roles.processes
    before = getattr(processes, "serial", None)
    try:
        return call()
    except (ConnectionResetError, ConnectionAbortedError) as exc:
        if type(before) is not int or getattr(processes, "serial", None) != before:
            raise
        recorder = getattr(roles, "transport_retry_recorder", None)
        if recorder is None or not recorder(role, exc, invocation_id):
            raise
    return call()


class RelayTransport:
    """The relay exchange seam (the ``processes`` of this transport). ``serial`` counts the
    exchanges that began writing request bytes; a failure that leaves it unchanged provably
    sent nothing."""

    def __init__(self, host, port, timeout):
        self.host = host
        self.port = port
        self.timeout = timeout
        self.serial = 0

    def run(self, method, path, body, headers):
        """One exchange; returns (status, raw body bytes, at most MAX_RESPONSE + 1)."""
        conn = http.client.HTTPConnection(self.host, self.port, timeout=self.timeout)
        try:
            conn.connect()  # an OSError here wrote nothing
            self.serial += 1  # from here request bytes may be on the wire
            conn.request(method, path, body=body, headers=headers)
            response = conn.getresponse()
            return response.status, response.read(MAX_RESPONSE + 1)
        finally:
            conn.close()


class RelayRoles:
    def __init__(
        self,
        url,
        token,
        run_id,
        budget=5,
        model=None,
        *,
        timeout=180,
        max_body=DEFAULT_MAX_BODY,
    ):
        parts = urlsplit(url or "")
        if parts.scheme != "http" or not parts.hostname or parts.path not in ("", "/"):
            raise Refused("relay url must be http://host:port", gate="transition")
        if not isinstance(token, str) or len(token) < 32:
            raise Refused("relay token missing or too short", gate="authorization")
        if not isinstance(run_id, str) or not run_id:
            raise Refused("relay run id missing", gate="authorization")
        if not _finite(timeout) or timeout <= 0:
            raise Refused("timeout must be a positive number", gate="transition")
        if type(max_body) is not int or not 1 <= max_body <= DEFAULT_MAX_BODY:
            raise Refused(
                f"max_body must be an integer in 1..{DEFAULT_MAX_BODY}", gate="transition"
            )
        self.host = parts.hostname
        self.port = parts.port or 80
        self._token = token  # never logged, never placed in a receipt
        self.run_id = run_id
        self.budget = budget
        self.spent = 0.0
        self.model = model
        self.timeout = timeout
        self.max_body = max_body
        self.processes = RelayTransport(self.host, self.port, timeout)
        self.receipts = []
        self.sessions = set()
        self.unknown_outcomes = []

    @classmethod
    def from_env(cls, environ=None, **kwargs):
        """Read the relay settings and REMOVE every ``SIMKIT_RELAY_*`` name from the mapping
        read (``os.environ`` by default), so no tool child inherits the run token. A second
        call in the same process reuses what the first one consumed from ``os.environ``."""
        live = environ is None
        env = os.environ if live else environ
        values = {name: env.get(name) for name in (ENV_URL, ENV_TOKEN, ENV_RUN, ENV_MODEL)}
        for name in [name for name in env if name.startswith(ENV_PREFIX)]:
            env.pop(name, None)
        if live:
            for name, value in values.items():
                if value is None:
                    values[name] = _CONSUMED.get(name)
                else:
                    _CONSUMED[name] = value
        kwargs.setdefault("model", values[ENV_MODEL] or None)
        return cls(values[ENV_URL], values[ENV_TOKEN], values[ENV_RUN], **kwargs)

    def __repr__(self):  # keep the token out of any accidental repr/log
        return f"RelayRoles(host={self.host!r}, port={self.port}, run_id={self.run_id!r})"

    def _headers(self, body):
        return {
            "Authorization": "Bearer " + self._token,
            "X-Simkit-Run": self.run_id,
            "Content-Type": "application/json",
            "Content-Length": str(len(body)),
        }

    def health(self):
        """Authenticated reachability check; sends no role request and spends nothing."""
        conn = http.client.HTTPConnection(self.host, self.port, timeout=self.timeout)
        try:
            conn.request("GET", HEALTH_PATH, headers=self._headers(b""))
            response = conn.getresponse()
            raw = response.read(MAX_RESPONSE + 1)
            status = response.status
        except OSError as exc:
            raise Refused(
                f"relay health check failed: {type(exc).__name__}", gate="transition"
            ) from exc
        finally:
            conn.close()
        try:
            value = json.loads(raw)
        except ValueError:
            value = None
        if status != 200 or not isinstance(value, dict) or value.get("outcome") != "OK":
            raise Refused(f"relay health check refused (HTTP {status})", gate="transition")
        return value

    def ask(self, role, payload):
        gate = role_gate(role)
        if not isinstance(role, str) or not role:
            raise Refused("role must be a non-empty string", gate=gate)
        if self.budget - self.spent < 0.05:
            raise Refused("aggregate model budget exhausted", gate="budget")
        try:
            input_hash = digest(payload)
            encoded = dedup_encode(payload)
            request = (
                {"role": role, "payload": payload}
                if encoded is None
                else {
                    "role": role,
                    **encoded,
                }
            )
            body = json.dumps(request, allow_nan=False).encode()
        except (TypeError, ValueError) as exc:
            raise Refused(f"{role} payload is not strict JSON: {exc}", gate=gate) from exc
        encoding = None if encoded is None else DEDUP_ENCODING
        if len(body) > self.max_body:  # the body actually sent: encoded when dedup applies
            raise Refused(
                f"{role} relay request is {len(body)} bytes, over the {self.max_body} cap",
                gate=gate,
            )
        invocation = str(uuid.uuid4())
        dispatch_context = getattr(self, "dispatch_context", None)
        if dispatch_context is not None:
            self.dispatch_observation = {
                "attempt_id": dispatch_context["attempt_id"],
                "invocation_id": invocation,
                "process_boundary": "NOT_ENTERED",
            }
        spent_before = self.spent
        # Reserve the remaining ceiling before anything is sent, exactly as KongRoles does.
        self.spent = self.budget
        if dispatch_context is not None:
            self.dispatch_observer(dict(self.dispatch_observation))
        serial_before = self.processes.serial
        try:
            status, raw = _transport_call(
                self,
                role,
                lambda: self.processes.run("POST", ASK_PATH, body, self._headers(body)),
                invocation,
            )
        except Exception as exc:
            if self.processes.serial == serial_before:
                self.spent = spent_before  # no exchange wrote a byte
                raise Refused(
                    f"{role} relay unreachable before sending: {type(exc).__name__}", gate=gate
                ) from exc
            if dispatch_context is not None:
                self.dispatch_observation["process_boundary"] = "ENTERED"
            fault = classify_fault(error_type=type(exc).__name__)
            self._unknown(role, invocation, f"relay exchange failed: {type(exc).__name__}", fault)
        if dispatch_context is not None:
            self.dispatch_observation.update(process_boundary="RETURNED", http_status=status)
        harness = classify_fault(kind="harness_error")  # a reply that is not a relay envelope
        if len(raw) > MAX_RESPONSE:
            self._unknown(
                role, invocation, "relay response over size cap", {"status": status, **harness}
            )
        try:
            envelope = json.loads(raw)
            if (
                not isinstance(envelope, dict)
                or envelope.get("outcome") not in ("SUCCESS", "REFUSED", "UNKNOWN")
                or not isinstance(envelope.get("relay_id"), str)
            ):
                raise ValueError("not a relay envelope")
        except ValueError:
            self._unknown(
                role, invocation, "unparseable relay response", {"status": status, **harness}
            )
        relay_id = envelope["relay_id"]
        if envelope["outcome"] == "UNKNOWN" or (
            envelope["outcome"] == "REFUSED" and type(envelope.get("sent_to_gateway")) is not bool
        ):
            evidence = envelope.get("evidence")
            evidence = evidence if isinstance(evidence, dict) else {}
            kept = {k: evidence.get(k) for k in UNKNOWN_EVIDENCE}
            if kept["fault_class"] not in (TRANSIENT, DETERMINISTIC):
                kept.update(classify_fault(kept["status"], kept["error_type"]))
            kept["relay_status"] = status
            self._unknown(role, invocation, "relay reports outcome UNKNOWN", kept, relay_id)
        if envelope["outcome"] == "REFUSED":
            billed = envelope.get("billed_usd")
            if envelope["sent_to_gateway"] is False:
                self.spent = spent_before  # the relay proved nothing was forwarded
            elif _finite(billed):
                self.spent = spent_before + billed
            reason = envelope.get("reason")
            reason = reason if isinstance(reason, str) else "no reason given"
            if envelope.get("reason_code") == SPEND_CAP_CODE:
                # The relay's spend guard refused before forwarding: the run is out of budget.
                raise Refused(f"{role} relay spend cap ({relay_id}): {reason}", gate="budget")
            raise Refused(f"{role} relay refused ({relay_id}): {reason}", gate=gate)
        if status != 200:
            self._unknown(
                role, invocation, "SUCCESS envelope with non-200 status", harness, relay_id
            )
        value, receipt = envelope.get("value"), envelope.get("receipt")
        try:
            optional = OPTIONAL_RECEIPT_FIELDS.get(role, frozenset())
            if not isinstance(receipt, dict) or not (
                RECEIPT_FIELDS <= set(receipt) <= RECEIPT_FIELDS | optional
            ):
                raise ValueError("receipt fields differ from the KongRoles receipt + relay fields")
            cost = receipt["cost_usd"]
            if _finite(cost):
                self.spent = spent_before + cost
            elif cost is not None:
                raise ValueError("receipt cost is not null or a finite non-negative number")
            if self.spent > self.budget:
                raise ValueError("aggregate budget exhausted")
            if receipt["relay_id"] != relay_id:
                raise ValueError("receipt relay_id differs from the envelope")
            if receipt["role"] != role or receipt["input_hash"] != input_hash:
                raise ValueError("receipt is not for this request")
            sizes = receipt["transport_bytes"]
            if receipt["transport_encoding"] != encoding or not isinstance(sizes, dict):
                raise ValueError("receipt transport encoding differs from the request sent")
            if encoding is not None and sizes.get("request_body_bytes") != len(body):
                raise ValueError("receipt transport sizes are not for this request")
            if not isinstance(value, dict):
                raise ValueError("role output must be an object")
            if receipt["output_hash"] != digest(value):
                raise ValueError("receipt output hash does not match the answer")
            if not isinstance(receipt["model_observed"], str) or not receipt["model_observed"]:
                raise ValueError("response carries no model identity")
            if self.model is not None and receipt["model_requested"] != self.model:
                raise ValueError("relay requested a different model")
            if receipt["transport"] != TRANSPORT or receipt["mode"] != "live":
                raise ValueError("receipt is not a live Kong transport receipt")
            session = receipt["session_id"]
            if not isinstance(session, str) or not session or session != receipt["response_id"]:
                raise ValueError("session_id is not the observed provider response_id")
            if session in self.sessions:
                raise ValueError("repeated independent session identity")
        except (ValueError, TypeError) as exc:
            raise Refused(f"invalid {role} relay response: {exc}", gate=gate) from exc
        self.sessions.add(receipt["session_id"])
        self.receipts.append(dict(receipt))
        return value

    def _unknown(self, role, invocation, reason, evidence, relay_id=None):
        # Keep the reservation: the request may have been forwarded and billed.
        record = {
            "role": role,
            "invocation_id": invocation,
            "relay_id": relay_id,
            "outcome": "UNKNOWN",
            **evidence,
            "reason": reason,
        }
        if "reason" in evidence and evidence["reason"] is not None:
            record["relay_reason"] = evidence["reason"]
        self.unknown_outcomes.append(record)
        raise RelayOutcomeUnknown(f"{role} relay outcome UNKNOWN: {reason}", record)


